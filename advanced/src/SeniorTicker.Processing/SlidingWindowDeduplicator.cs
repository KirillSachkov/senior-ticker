using SeniorTicker.Application;
using SeniorTicker.Domain;

namespace SeniorTicker.Processing;

/// <summary>
/// Отсеивает повторы тиков. Один и тот же тик может прийти дважды: из-за переподключений к бирже и
/// пересекающихся источников. Дедупликатор отвечает на один вопрос: видели ли мы такой тик недавно.
/// Если да, это повтор, и его выкидывают.
///
/// Недавно тут значит скользящее окно времени длиной _window (например, последние 60 секунд). Мы
/// смотрим не на всю историю, а только на это окно. Так и повторы ловятся, и память ограничена:
/// ключи старше окна забываются, набор не растёт без предела.
///
/// Внутри две структуры, каждая под свою задачу. _seen за O(1) отвечает, есть ли такой ключ в окне.
/// _expiry хранит те же ключи по времени их выхода из окна, чтобы дёшево убирать просроченные.
///
/// SINGLE-WRITER: метод вызывает только один поток. Маршрутизация устроена так, что один ключ всегда
/// попадает в один и тот же поток, поэтому HashSet и Queue берём обычные, без блокировок: гонок нет
/// по построению. Это разбираем дальше, в блоке про очереди.
///
/// Если бы сюда заходило несколько потоков сразу, сломалось бы в трёх местах. (1) HashSet и Queue не
/// потокобезопасны: параллельные _seen.Add/Remove или _expiry.Enqueue/Dequeue рвут их внутреннее
/// состояние, вплоть до потерянных записей и исключений при рехеше. (2) Evict, Add и Enqueue это одна
/// неделимая правка сразу двух структур: на гонке ключ может попасть в _seen, но не в _expiry (тогда он
/// никогда не выйдет из окна), или наоборот. (3) Сроки в очереди обязаны идти по возрастанию, а это
/// держится на том, что now берётся по очереди одним потоком; при параллели порядок инвертируется, и
/// Evict перестаёт работать. Поэтому правильный ответ тут не лок, а один поток на ключ.
///
/// Ключ это точный TickKey, а не 32-битный хеш, поэтому разные тики не схлопываются по ложному совпадению.
/// </summary>
public sealed class SlidingWindowDeduplicator : IDeduplicator
{
    private readonly TimeSpan _window;    // ширина окна: насколько назад тик ещё считается повтором
    private readonly TimeProvider _time;  // источник времени; в тестах подменяется, поэтому не DateTimeOffset.UtcNow напрямую

    // Ключи, которые прямо сейчас в окне. Единственная задача этого множества: за O(1) ответить,
    // встречался ли такой ключ. Когда ключу пора уходить, оно само не знает, за это отвечает очередь.
    private readonly HashSet<TickKey> _seen = [];

    // Те же ключи, выстроенные по времени их выхода из окна (Expiry = когда впустили + _window). Окно
    // фиксированной длины, а время идёт только вперёд, поэтому впущенный раньше и выходит раньше: это
    // обычная очередь (FIFO), и сроки в ней всегда по возрастанию. Поэтому просроченные снимаются
    // с головы, без перебора всего множества.
    private readonly Queue<(DateTimeOffset Expiry, TickKey Key)> _expiry = new();

    public SlidingWindowDeduplicator(TimeSpan window, TimeProvider time)
    {
        // Окно нулевой или отрицательной длины бессмысленно: окна нет, ловить нечего. Падаем сразу
        // на старте, а не работаем молча мимо.
        ArgumentOutOfRangeException.ThrowIfLessThanOrEqual(window, TimeSpan.Zero);
        _window = window;
        _time = time;
    }

    /// <summary>true, если такой тик уже видели в окне (повтор); false для нового тика.</summary>
    public bool IsDuplicate(in Tick tick)
    {
        var now = _time.GetUtcNow();

        // Шаг 1. Сдвигаем окно к текущему моменту: убираем всё, что уже устарело. После этого в _seen
        // лежат ровно те ключи, что ещё в окне, и проверка ниже честная.
        Evict(now);

        // Шаг 2. Пробуем добавить ключ. HashSet.Add возвращает false, если такой ключ там уже был.
        // Раз он в окне, значит этот тик мы уже видели за последние _window: это повтор.
        if (!_seen.Add(tick.Key))
            return true;

        // Шаг 3. Ключ новый, тик принят. Запоминаем момент его выхода из окна (now + _window), положив
        // пару в хвост очереди. Возвращаем false: не повтор, пропускаем дальше.
        _expiry.Enqueue((now + _window, tick.Key));
        return false;
    }

    // Убирает из окна все ключи, чей срок к моменту now уже истёк.
    private void Evict(DateTimeOffset now)
    {
        // Смотрим только в голову очереди, там самый ранний срок. Пока он истёк (Expiry <= now): снимаем
        // запись с очереди и забываем ключ в множестве. На первом ещё живом останавливаемся: сроки по
        // возрастанию, значит дальше все свежее. Каждый ключ проходит через очередь ровно один раз за
        // свою жизнь, поэтому в среднем это O(1) на тик.
        while (_expiry.TryPeek(out var head) && head.Expiry <= now)
        {
            _expiry.Dequeue();
            _seen.Remove(head.Key);
        }
    }
}
